pub use ipc::RenameMode;

/// `nebula kill`.
pub fn run_kill() -> Result<()> {
    runtime()?.block_on(async {
        if ipc::kill_daemon().await? {
            println!("kete daemon shut down");
        } else {
            println!("no kete daemon running");
        }
        Ok(())
    })
}
